/**
 * Codifica texto Unicode a bytes CP858 para impresoras ESC/POS.
 * Mapeo explícito de acentos españoles — obligatorio para impresión correcta.
 */

/** Unicode → byte CP858 (basado en CP850 + € en 0xD5) */
const UNICODE_TO_CP858: Readonly<Record<number, number>> = {
  0x20ac: 0xd5, // €
  0x00c7: 0x80, // Ç
  0x00fc: 0x81, // ü
  0x00e9: 0x82, // é
  0x00e2: 0x83, // â
  0x00e4: 0x84, // ä
  0x00e0: 0x85, // à
  0x00e5: 0x86, // å
  0x00e7: 0x87, // ç
  0x00ea: 0x88, // ê
  0x00eb: 0x89, // ë
  0x00e8: 0x8a, // è
  0x00ef: 0x8b, // ï
  0x00ee: 0x8c, // î
  0x00ec: 0x8d, // ì
  0x00c4: 0x8e, // Ä
  0x00c5: 0x8f, // Å
  0x00c9: 0x90, // É
  0x00e6: 0x91, // æ
  0x00c6: 0x92, // Æ
  0x00f4: 0x93, // ô
  0x00f6: 0x94, // ö
  0x00f2: 0x95, // ò
  0x00fb: 0x96, // û
  0x00f9: 0x97, // ù
  0x00ff: 0x98, // ÿ
  0x00d6: 0x99, // Ö
  0x00dc: 0x9a, // Ü
  0x00f8: 0x9b, // ø
  0x00a3: 0x9c, // £
  0x00d8: 0x9d, // Ø
  0x00d7: 0x9e, // ×
  0x00e1: 0xa0, // á
  0x00ed: 0xa1, // í
  0x00f3: 0xa2, // ó
  0x00fa: 0xa3, // ú
  0x00f1: 0xa4, // ñ
  0x00d1: 0xa5, // Ñ
  0x00aa: 0xa6, // ª
  0x00ba: 0xa7, // º
  0x00bf: 0xa8, // ¿
  0x00ae: 0xa9, // ®
  0x00ac: 0xac, // ¬
  0x00a1: 0xad, // ¡
  0x00ab: 0xae, // «
  0x00bb: 0xaf, // »
  0x00c1: 0xb5, // Á
  0x00cd: 0xd6, // Í
  0x00d3: 0xe0, // Ó
  0x00da: 0xe9, // Ú
};

export function encodeToCp858(text: string): Buffer {
  const bytes = new Uint8Array(text.length);
  let len = 0;

  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if (code < 0x80) {
      bytes[len++] = code;
      continue;
    }
    const mapped = UNICODE_TO_CP858[code];
    if (mapped !== undefined) {
      bytes[len++] = mapped;
      continue;
    }
    if (code <= 0xff) {
      bytes[len++] = code;
      continue;
    }
    bytes[len++] = 0x3f;
  }

  return Buffer.from(bytes.subarray(0, len));
}
